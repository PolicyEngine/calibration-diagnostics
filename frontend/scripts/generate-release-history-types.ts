/**
 * Generates lib/microcosm/release-history-documents.ts (calibration-diagnostics#224): the
 * TypeScript types of the documents the Python producer and this side hand each other, from the
 * JSON Schemas in release_history/schemas/. Both languages work from the one set of schemas, so
 * no hand-written copy can drift from what the other side writes.
 *
 *   bun run scripts/generate-release-history-types.ts
 *
 * Run it after changing a schema. scripts/generate-release-history-types.test.ts fails while the
 * committed file is stale (with UPDATE_GENERATED=1 it rewrites it).
 */
import { readdir, readFile, writeFile } from "node:fs/promises";
import { join, relative } from "node:path";

import { compile, type JSONSchema, type Options } from "json-schema-to-typescript";

export const SCHEMA_FOLDER = join(import.meta.dir, "..", "..", "release_history", "schemas");
export const GENERATED_FILE = join(import.meta.dir, "..", "lib", "microcosm", "release-history-documents.ts");

/** Each document's TypeScript name, by its schema's file name (`<kind>.schema.json`). */
const TYPE_NAMES: Readonly<Record<string, string>> = {
  attempt: "AttemptReport",
  labels: "LabelsDocument",
  panel: "PanelDocument",
  "planned-point": "PlannedPoint",
  point: "MeasurementDocument",
  series: "SeriesRecord",
  timeline: "Timeline",
};

const HEADER = `/**
 * Generated by scripts/generate-release-history-types.ts from the JSON Schemas in
 * release_history/schemas/. Do not edit: change a schema, then run
 * \`bun run scripts/generate-release-history-types.ts\` in frontend/.
 */
`;

const OPTIONS: Partial<Options> = {
  bannerComment: "",
  // A size limit is the schema's check, not a type: an array stays an array, never a tuple.
  ignoreMinAndMaxItems: true,
};

// Keywords that only describe a schema. A schema of these alone, such as a field copied as an
// upstream document holds it, allows any JSON value; json-schema-to-typescript would make it an
// object, so the generator marks it `unknown` first.
const ANNOTATIONS = new Set([
  "$comment",
  "default",
  "deprecated",
  "description",
  "examples",
  "readOnly",
  "title",
  "writeOnly",
]);
// Where draft 2020-12 nests schemas: maps of them, lists of them, and single ones.
const SCHEMA_MAPS = ["properties", "patternProperties", "$defs", "definitions", "dependentSchemas"];
const SCHEMA_LISTS = ["anyOf", "oneOf", "allOf", "prefixItems"];
const SCHEMA_VALUES = [
  "additionalProperties",
  "items",
  "contains",
  "not",
  "if",
  "then",
  "else",
  "propertyNames",
  "unevaluatedProperties",
  "unevaluatedItems",
];

type SchemaNode = Record<string, unknown>;

function isSchemaNode(value: unknown): value is SchemaNode {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

/** The schema with every subschema that allows any value marked `unknown`. */
export function markAnyValue(schema: SchemaNode): SchemaNode {
  if (Object.keys(schema).every((keyword) => ANNOTATIONS.has(keyword))) {
    return { ...schema, tsType: "unknown" };
  }
  const marked: SchemaNode = { ...schema };
  for (const keyword of SCHEMA_MAPS) {
    const children = marked[keyword];
    if (!isSchemaNode(children)) continue;
    marked[keyword] = Object.fromEntries(
      Object.entries(children).map(([name, child]) => [name, isSchemaNode(child) ? markAnyValue(child) : child]),
    );
  }
  for (const keyword of SCHEMA_LISTS) {
    const children = marked[keyword];
    if (!Array.isArray(children)) continue;
    marked[keyword] = children.map((child) => (isSchemaNode(child) ? markAnyValue(child) : child));
  }
  for (const keyword of SCHEMA_VALUES) {
    const child = marked[keyword];
    if (isSchemaNode(child)) marked[keyword] = markAnyValue(child);
  }
  return marked;
}

/** The generated file's text: one exported type per schema, in file-name order. */
export async function generateReleaseHistoryTypes(): Promise<string> {
  const files = (await readdir(SCHEMA_FOLDER)).filter((name) => name.endsWith(".schema.json")).sort();
  const declarations: string[] = [];
  for (const file of files) {
    const kind = file.slice(0, -".schema.json".length);
    if (!Object.hasOwn(TYPE_NAMES, kind)) {
      throw new Error(`${file} has no TypeScript name: add one to TYPE_NAMES in ${relative(process.cwd(), import.meta.path)}.`);
    }
    const schema = JSON.parse(await readFile(join(SCHEMA_FOLDER, file), "utf8")) as SchemaNode;
    // The type takes its name from TYPE_NAMES, never from the schema's title or id.
    const { $id: _id, title: _title, ...named } = schema;
    declarations.push((await compile(markAnyValue(named) as JSONSchema, TYPE_NAMES[kind], OPTIONS)).trim());
  }
  return `${HEADER}\n${declarations.join("\n\n")}\n`;
}

if (import.meta.main) {
  await writeFile(GENERATED_FILE, await generateReleaseHistoryTypes());
  console.log(`Wrote ${relative(process.cwd(), GENERATED_FILE)}.`);
}
